import { readFileSync } from "node:fs"
import { describe, expect, it } from "vitest"
import { generateCss, loadTokens } from "./build-tokens.mjs"

const css = { selector: ":root", layer: "base" }
const group = (tokens) => ({ $extensions: { "com.rolvix.css": css }, ...tokens })

describe("design token generation", () => {
  it("validates every source token's value, type and aliases", async () => {
    const sets = await loadTokens()
    expect(Object.keys(sets).length).toBeGreaterThan(0)
    expect(() => generateCss(sets)).not.toThrow()
  })

  it("matches the checked-in CSS without writing any files", async () => {
    const generated = generateCss(await loadTokens())
    expect(readFileSync("src/styles/tokens.generated.css", "utf8")).toBe(generated)
  })

  it("keeps aliases as CSS references so runtime theme overrides still propagate", () => {
    expect(generateCss({ light: group({
      primary: { $type: "color", $value: { colorSpace: "oklch", components: [0.54, 0.19, 264] } },
      "chart-1": { $type: "color", $value: "{light.primary}" },
    }) })).toBe(`/* Generated by scripts/build-tokens.mjs; do not edit. */

@layer base {
  :root {
    --primary: oklch(0.54 0.19 264);
    --chart-1: var(--primary);
  }
}
`)
  })

  it.each([
    [{ $type: "color" }, /Missing \$value/],
    [{ $value: "#fff" }, /Invalid \$type/],
    [{ $type: "string", $value: "200ms" }, /Invalid \$type/],
    [{ $type: "duration", $value: "200ms" }, /Invalid duration/],
    [{ $type: "dimension", $value: { value: 4, unit: "em" } }, /Invalid dimension/],
    [{ $type: "color", $value: "oklch(1 0 0)" }, /Invalid color/],
    [{ $type: "cubicBezier", $value: [2, 0, 0, 1] }, /Invalid cubicBezier/],
    [{ $type: "color", $value: "{light.missing}" }, /Unknown token alias/],
    [{ $type: "color", $value: "{light.bad}" }, /Circular token alias/],
  ])("rejects malformed tokens and unresolved aliases (%j)", (bad, message) => {
    expect(() => generateCss({ light: group({ bad }) })).toThrow(message)
  })

  it("rejects aliases whose types disagree", () => {
    expect(() => generateCss({ light: group({
      base: { $type: "duration", $value: { value: 200, unit: "ms" } },
      bad: { $type: "color", $value: "{light.base}" },
    }) })).toThrow(/Alias type mismatch/)
  })

  it("serializes structured values while preserving CSS shadow colors and spring feature detection", () => {
    const dimension = (value) => ({ value, unit: "px" })
    const generated = generateCss({ light: group({
      radius: { $type: "dimension", $value: { value: 0.625, unit: "rem" } },
      fast: { $type: "duration", $value: { value: 120, unit: "ms" } },
      spring: { $type: "cubicBezier", $value: [0.34, 1.56, 0.64, 1],
        $extensions: { "com.rolvix.css": { supports: { condition: "(transition-timing-function: linear(0, 1))", value: "linear(0, 1.08 37%, 1)" } } } },
      "shadow-color": { $type: "color", $value: { colorSpace: "hsl", components: [266, 30, 20] },
        $extensions: { "com.rolvix.css": { channels: true } } },
      "shadow-xs": { $type: "shadow", $value: [{
        offsetX: dimension(0), offsetY: dimension(1), blur: dimension(2), spread: dimension(0),
        color: { colorSpace: "hsl", components: [266, 30, 20], alpha: 0.05 },
      }], $extensions: { "com.rolvix.css": { shadowColor: "--shadow-color" } } },
      brand: { $type: "color", $value: { colorSpace: "srgb", components: [77 / 255, 106 / 255, 146 / 255] },
        $extensions: { "com.rolvix.css": { format: "hex" } } },
    }) })
    expect(generated).toContain("--radius: 0.625rem;")
    expect(generated).toContain("--fast: 120ms;")
    expect(generated).toContain("--spring: cubic-bezier(0.34, 1.56, 0.64, 1);")
    expect(generated).toContain("--shadow-color: 266 30% 20%;")
    expect(generated).toContain("--shadow-xs: 0 1px 2px 0 hsl(var(--shadow-color) / 0.05);")
    expect(generated).toContain("--brand: #4d6a92;")
    expect(generated).toContain("@supports (transition-timing-function: linear(0, 1)) {\n    :root {\n      --spring: linear(0, 1.08 37%, 1);")
  })

  it("keeps portal light-dark colors scoped to the portal and validates both references", () => {
    const portal = {
      $extensions: { "com.rolvix.css": { selector: ".portal-shell" } },
      light: { $type: "color", $value: { colorSpace: "srgb", components: [0, 0, 0] } },
      dark: { $type: "color", $value: { colorSpace: "srgb", components: [1, 1, 1] } },
      free: { $type: "color", $value: "{portal.light}", $extensions: { "com.rolvix.css": { lightDark: "{portal.dark}" } } },
    }
    expect(generateCss({ portal })).toContain(".portal-shell {\n  --light: rgb(0 0 0);\n  --dark: rgb(255 255 255);\n  --free: light-dark(var(--light), var(--dark));")
    portal.free.$extensions["com.rolvix.css"].lightDark = "{portal.missing}"
    expect(() => generateCss({ portal })).toThrow(/Unknown token alias/)
  })
})
