const CUSTOMER_VISIBLE_FILE_ACCEPT =
  "image/jpeg,image/png,image/webp,.jpg,.jpeg,.png,.webp"
const INTERNAL_FILE_ACCEPT = ".pdf,.stl,.step,.stp,.dxf,application/pdf"

function emptyProductForm(): CatalogProductFormValues {
  return {
    name: "",
    code: "",
    description: "",
    price: "",
    currency: "BRL",
  }
}

export function CatalogProductsPage() {
  const { t, i18n } = useTranslation()
  const { can } = usePermissions()
  const canManage = can("catalog.products.manage")

  const [products, setProducts] = useState<CatalogProduct[]>([])
  const [requests, setRequests] = useState<ProductRequest[]>([])
  const [loading, setLoading] = useState(true)
  const [loadError, setLoadError] = useState<string | null>(null)
  const [columnFilters, setColumnFilters] = useState<ColumnFiltersState>([])
  const [taxonomyOptions, setTaxonomyOptions] = useState<TaxonomyOptions>({ categories: [], tags: [] })
  const [searchParams, setSearchParams] = useSearchParams()
  const categoryParam = searchParams.get("category")
  const tagsParam = searchParams.get("tags")
  const taxonomyFilter = useMemo(() => {
    const query = taxonomyQueryFromSearch(new URLSearchParams({
      ...(categoryParam == null ? {} : { category: categoryParam }),
      ...(tagsParam == null ? {} : { tags: tagsParam }),
    }))
    return {
      categoryId: query.category ?? null,
      tagIds: [...(query.tags ?? [])],
    }
  }, [categoryParam, tagsParam])
  const [dialogOpen, setDialogOpen] = useState(false)
  const [editing, setEditing] = useState<CatalogProduct | null>(null)
  const [statusBusyId, setStatusBusyId] = useState<string | null>(null)
  const [fileBusy, setFileBusy] = useState(false)
  const [uploadVisibility, setUploadVisibility] =
    useState<CatalogFileVisibility>("CustomerVisible")
  const [createdProductId, setCreatedProductId] = useState<string | null>(null)
  const [pendingFiles, setPendingFiles] = useState<PendingFile[]>([])
  const [fileError, setFileError] = useState<string | null>(null)
  const [productPendingDeactivate, setProductPendingDeactivate] =
    useState<CatalogProduct | null>(null)
  const [codeManuallyEdited, setCodeManuallyEdited] = useState(false)
  const [operationInFlight, setOperationInFlight] = useState(false)
  const saveLockRef = useRef<SaveCatalogProductCreateLock>({ inFlight: false })
  const loadGenerationRef = useRef(0)
  const loadAbortControllerRef = useRef<AbortController | null>(null)

  const form = useForm<CatalogProductFormValues>({
    resolver: zodResolver(catalogProductFormSchema),
    defaultValues: emptyProductForm(),
  })
  const watchedValues = useWatch({ control: form.control })
  const isFormValid = catalogProductFormSchema.safeParse(watchedValues).success
  const saveBlockers = catalogProductSaveBlockerKeys(watchedValues)

  const reload = useCallback(async () => {
    loadAbortControllerRef.current?.abort()
    const controller = new AbortController()
    loadAbortControllerRef.current = controller
    const generation = ++loadGenerationRef.current
    setLoading(true)
    try {
      const [nextProducts, nextRequests] = await Promise.all([
        listCatalogProducts(
          { category: taxonomyFilter.categoryId, tags: taxonomyFilter.tagIds },
          { signal: controller.signal },
        ),
        listProductRequests({ signal: controller.signal }),
      ])
      if (controller.signal.aborted || generation !== loadGenerationRef.current) {
        return
      }
      setProducts(nextProducts)
      setRequests(nextRequests)
      setLoadError(null)
    } catch (error) {
      if (controller.signal.aborted || generation !== loadGenerationRef.current) {
        return
      }
      setLoadError(
        error instanceof Error ? error.message : t("apiErrors.loadCatalogProducts"),
      )
    } finally {
      if (generation === loadGenerationRef.current) {
        setLoading(false)
      }
    }
  }, [t, taxonomyFilter.categoryId, taxonomyFilter.tagIds])

  useEffect(() => {
    void reload()
    return () => loadAbortControllerRef.current?.abort()
  }, [reload])

  const updateTaxonomyFilter = useCallback((next: { categoryId: string | null; tagIds: string[] }) => {
    setSearchParams((current) => setTaxonomySearchParams(current, {
      category: next.categoryId,
      tags: next.tagIds,
    }))
  }, [setSearchParams])

  useEffect(() => {
    void getCatalogTaxonomyOptions()
      .then(setTaxonomyOptions)
      .catch(() => setTaxonomyOptions({ categories: [], tags: [] }))
  }, [])

  useEffect(() => {
    if (!dialogOpen) {
      return
    }
    void getCatalogTaxonomyOptions()
      .then(setTaxonomyOptions)
      .catch(() => setTaxonomyOptions({ categories: [], tags: [] }))
  }, [dialogOpen])

  function resetDialogState() {
    setEditing(null)
    setCreatedProductId(null)
    setPendingFiles([])
    setFileError(null)
    setCodeManuallyEdited(false)
    setUploadVisibility("CustomerVisible")
    form.reset(emptyProductForm())
  }

  function openCreate() {
    resetDialogState()
    setDialogOpen(true)
  }

  function openEdit(product: CatalogProduct) {
    setCreatedProductId(null)
    setPendingFiles([])
    setFileError(null)
    setCodeManuallyEdited(false)
    setUploadVisibility("CustomerVisible")
    setEditing(product)
    form.reset({
      name: product.name,
      code: product.code ?? "",
      description: product.description ?? "",
      price: product.price == null ? "" : String(product.price),
      currency: product.currency,
      ...(product.taxonomy ? { taxonomy: {
        categoryIds: product.taxonomy.categories.map((item) => item.id),
        tagIds: product.taxonomy.tags.map((item) => item.id),
      } } : {}),
    })
    setDialogOpen(true)
  }

  async function onSubmit(values: CatalogProductFormValues) {
    const priceTrimmed = values.price.trim()
    let price: number | null = null
    if (priceTrimmed.length > 0) {
      const parsed = Number(priceTrimmed.replace(",", "."))
      if (!Number.isFinite(parsed) || parsed < 0) {
        form.setError("price", { message: t("catalog.products.invalidPrice") })
        return
      }
      price = parsed
    }

    const body = toCatalogProductWriteBody(values, price)

    try {
      if (editing) {
        const updated = await updateCatalogProduct(editing.id, body)
        setEditing(updated)
        toast.success(t("catalog.products.toastUpdated"))
        await reload()
        return
      }

      setOperationInFlight(true)
      const result = await saveCatalogProductCreate({
        createdProductId,
        values: body,
        pendingFiles,
        createProduct: createCatalogProduct,
        uploadFile: uploadCatalogProductFile,
        lock: saveLockRef.current,
        onFilesChange: setPendingFiles,
      })

      if (result.skipped) {
        return
      }

      setCreatedProductId(result.productId)
      setPendingFiles(result.files)

      if (result.allUploaded) {
        toast.success(t("catalog.products.toastCreated"))
        resetDialogState()
        setDialogOpen(false)
        await reload()
        return
      }

      toast.error(t("catalog.products.files.partialFailure"))
      await reload()
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : t("apiErrors.saveCatalogProduct"),
      )
    } finally {
      if (!saveLockRef.current.inFlight) {
        setOperationInFlight(false)
      }
    }
  }

  function requestToggleActive(product: CatalogProduct) {
    if (product.isActive) {
      setProductPendingDeactivate(product)
      return
    }

    void toggleActive(product)
  }

  async function toggleActive(product: CatalogProduct) {
    setStatusBusyId(product.id)
    try {
      if (product.isActive) {
        await deactivateCatalogProduct(product.id)
        toast.success(t("catalog.products.toastDeactivated"))
      } else {
        await activateCatalogProduct(product.id)
        toast.success(t("catalog.products.toastActivated"))
      }
      await reload()
    } catch (error) {
      toast.error(
        error instanceof Error
          ? error.message
          : t("apiErrors.updateCatalogProductStatus"),
      )
    } finally {
      setStatusBusyId(null)
    }
  }

  async function onRetryPendingFile(clientId: string) {
    if (!createdProductId || operationInFlight) {
      return
    }

    setOperationInFlight(true)
    try {
      const result = await retryPendingCatalogFile({
        productId: createdProductId,
        pendingFiles,
        clientId,
        uploadFile: uploadCatalogProductFile,
        lock: saveLockRef.current,
        onFilesChange: setPendingFiles,
      })

      if (result.skipped) {
        return
      }

      setPendingFiles(result.files)

      if (result.allUploaded) {
        toast.success(t("catalog.products.toastCreated"))
        resetDialogState()
        setDialogOpen(false)
        await reload()
        return
      }

      toast.error(t("catalog.products.files.partialFailure"))
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : t("apiErrors.uploadCatalogFile"),
      )
    } finally {
      if (!saveLockRef.current.inFlight) {
        setOperationInFlight(false)
      }
    }
  }

  function describeFileRejection(file: File): string | null {
    const rejection = catalogFileRejection(file, uploadVisibility)
    if (rejection == null) {
      return null
    }

    return t(`catalog.products.files.${rejection}`, { name: file.name })
  }

  function queueCreateFiles(fileList: FileList | null) {
    if (!fileList || fileList.length === 0) {
      return
    }

    const accepted: PendingFile[] = []
    const rejected: string[] = []
    for (const file of Array.from(fileList)) {
      const message = describeFileRejection(file)
      if (message != null) {
        rejected.push(message)
        continue
      }

      accepted.push(newPendingCatalogFile(file, uploadVisibility))
    }

    if (accepted.length > 0) {
      setPendingFiles((current) => [...current, ...accepted])
    }
    setFileError(rejected.length > 0 ? rejected.join(" ") : null)
  }

  async function onUploadFile(file: File | undefined) {
    if (!file || !editing) {
      return
    }

    const rejection = describeFileRejection(file)
    if (rejection != null) {
      setFileError(rejection)
      return
    }

    setFileBusy(true)
    setFileError(null)
    try {
      await uploadCatalogProductFile(editing.id, file, uploadVisibility)
      const refreshed = await listCatalogProducts()
      setProducts(refreshed)
      const next = refreshed.find((item) => item.id === editing.id) ?? null
      setEditing(next)
      toast.success(t("catalog.products.toastFileUploaded"))
    } catch (error) {
      const message =
        error instanceof Error ? error.message : t("apiErrors.uploadCatalogFile")
      setFileError(message)
      toast.error(message)
    } finally {
      setFileBusy(false)
    }
  }

  async function onDeleteFile(fileId: string) {
    if (!editing) {
      return
    }
    setFileBusy(true)
    try {
      await deleteCatalogProductFile(editing.id, fileId)
      const refreshed = await listCatalogProducts()
      setProducts(refreshed)
      setEditing(refreshed.find((item) => item.id === editing.id) ?? null)
      toast.success(t("catalog.products.toastFileDeleted"))
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : t("apiErrors.deleteCatalogFile"),
      )
    } finally {
      setFileBusy(false)
    }
  }

  async function onOpenFile(fileId: string) {
    if (!editing) {
      return
    }
    try {
      const result = await getCatalogProductFileUrl(editing.id, fileId)
      window.open(result.url, "_blank", "noopener,noreferrer")
    } catch (error) {
      toast.error(
        error instanceof Error ? error.message : t("apiErrors.loadCatalogFileUrl"),
      )
    }
  }

  const columns = useMemo<ColumnDef<CatalogProduct>[]>(
    () => [
      {
        accessorKey: "name",
        header: ({ column }) => (
          <DataTableColumnFilterHeader
            column={column}
            title={t("catalog.products.columns.name")}
          />
        ),
      },
      {
        accessorKey: "code",
        header: ({ column }) => (
          <DataTableColumnFilterHeader
            column={column}
            title={t("catalog.products.columns.code")}
          />
        ),
        cell: ({ row }) => row.original.code ?? "—",
      },
      {
        id: "price",
        accessorFn: (row) =>
          formatCatalogMoney(row.price, row.currency, i18n.language) ??
          t("catalog.priceOnRequest"),
        header: ({ column }) => (
          <DataTableColumnFilterHeader
            column={column}
            title={t("catalog.products.columns.price")}
          />
        ),
      },
      {
        accessorKey: "isActive",
        header: ({ column }) => (
          <DataTableColumnFilterHeader
            column={column}
            title={t("catalog.products.columns.status")}
          />
        ),
        cell: ({ row }) => (
          <Badge variant={row.original.isActive ? "success" : "secondary"}>
            {row.original.isActive
              ? t("catalog.products.active")
              : t("catalog.products.inactive")}
          </Badge>
        ),
        filterFn: (row, _columnId, filterValue) => {
          if (typeof filterValue !== "string" || filterValue.trim() === "") {
            return true
          }
          const label = row.original.isActive
            ? t("catalog.products.active")
            : t("catalog.products.inactive")
          return label.toLowerCase().includes(filterValue.trim().toLowerCase())
        },
      },
      {
        id: "categories",
        accessorFn: (row) => row.taxonomy?.categories.map((item) => item.name).join(", ") ?? "",
        header: () => <TaxonomyFilterHeader title={t("taxonomy.categories")} options={taxonomyOptions} filter={taxonomyFilter} onChange={updateTaxonomyFilter} />,
        cell: ({ row }) => row.original.taxonomy?.categories.map((item) => item.name).join(", ") || "—",
      },
      {
        id: "tags",
        accessorFn: (row) => row.taxonomy?.tags.map((item) => item.name).join(", ") ?? "",
        header: () => <TaxonomyFilterHeader title={t("taxonomy.tags")} options={taxonomyOptions} filter={taxonomyFilter} onChange={updateTaxonomyFilter} />,
        cell: ({ row }) => row.original.taxonomy?.tags.map((item) => item.name).join(", ") || "—",
      },
      {
        id: "actions",
        enableColumnFilter: false,
        header: t("catalog.products.columns.actions"),
        cell: CatalogProductActionsCell,
      },
    ],
    [i18n.language, t, taxonomyFilter, taxonomyOptions, updateTaxonomyFilter],
  )

  const table = useReactTable({
    data: products,
    columns,
    state: { columnFilters },
    onColumnFiltersChange: setColumnFilters,
    meta: {
      onEdit: openEdit,
      onToggleActive: requestToggleActive,
      statusBusyId,
    },
    getCoreRowModel: getCoreRowModel(),
    getFilteredRowModel: getFilteredRowModel(),
  })

  const requestColumns = useMemo<ColumnDef<ProductRequest>[]>(
    () => [
      {
        accessorKey: "description",
        header: ({ column }) => (
          <DataTableColumnFilterHeader
            column={column}
            title={t("catalog.requests.columns.description")}
          />
        ),
      },
      {
        accessorKey: "quantity",
        header: t("catalog.requests.columns.quantity"),
        enableColumnFilter: false,
      },
      {
        accessorKey: "note",
        header: ({ column }) => (
          <DataTableColumnFilterHeader
            column={column}
            title={t("catalog.requests.columns.note")}
          />
        ),
        cell: ({ row }) => row.original.note ?? "—",
      },
      {
        accessorKey: "createdAt",
        header: t("catalog.requests.columns.createdAt"),
        enableColumnFilter: false,
        cell: ({ row }) =>
          new Intl.DateTimeFormat(i18n.language, {
            dateStyle: "short",
          }).format(new Date(row.original.createdAt)),
      },
    ],
    [i18n.language, t],
  )

  const [requestFilters, setRequestFilters] = useState<ColumnFiltersState>([])
  const requestTable = useReactTable({
    data: requests,
    columns: requestColumns,
    state: { columnFilters: requestFilters },
    onColumnFiltersChange: setRequestFilters,
    getCoreRowModel: getCoreRowModel(),
    getFilteredRowModel: getFilteredRowModel(),
  })

  const editingPreviewImages = editing
    ? selectCatalogProductImages(editing.files)
    : []

  return (
    <div className="space-y-8">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div className="space-y-1">
          <h1 className="text-xl font-semibold tracking-tight">
            {t("catalog.products.title")}
          </h1>
          <p className="text-sm text-muted-foreground">
            {t("catalog.products.subtitle")}
          </p>
        </div>
        <Can permission="catalog.products.manage">
          <Button type="button" onClick={openCreate}>
            <Plus data-icon="inline-start" />
            {t("catalog.products.create")}
          </Button>
        </Can>
      </div>

      {loadError ? (
        <p className="text-sm text-destructive">{loadError}</p>
      ) : null}

      <div className="rounded-xl border border-border">
        <Table>
          <TableHeader>
            {table.getHeaderGroups().map((headerGroup) => (
              <TableRow key={headerGroup.id}>
                {headerGroup.headers.map((header) => (
                  <TableHead key={header.id}>
                    {header.isPlaceholder
                      ? null
                      : flexRender(
                          header.column.columnDef.header,
                          header.getContext(),
                        )}
                  </TableHead>
                ))}
              </TableRow>
            ))}
          </TableHeader>
          <TableBody>
            {loading ? (
              <TableRowsSkeleton columns={7} rows={4} />
            ) : table.getRowModel().rows.length === 0 ? (
              <TableRow>
                <TableCell colSpan={7} className="h-24 text-center">
                  {t("catalog.products.empty")}
                </TableCell>
              </TableRow>
            ) : (
              table.getRowModel().rows.map((row) => (
                <TableRow key={row.id}>
                  {row.getVisibleCells().map((cell) => (
                    <TableCell key={cell.id}>
                      {flexRender(
                        cell.column.columnDef.cell,
                        cell.getContext(),
                      )}
                    </TableCell>
                  ))}
                </TableRow>
              ))
            )}
          </TableBody>
        </Table>
      </div>

      <section className="space-y-3">
        <div className="space-y-1">
          <h2 className="text-lg font-semibold">
            {t("catalog.requests.title")}
          </h2>
          <p className="text-sm text-muted-foreground">
            {t("catalog.requests.subtitle")}
          </p>
        </div>
        <div className="rounded-xl border border-border">
          <Table>
            <TableHeader>
              {requestTable.getHeaderGroups().map((headerGroup) => (
                <TableRow key={headerGroup.id}>
                  {headerGroup.headers.map((header) => (
                    <TableHead key={header.id}>
                      {header.isPlaceholder
                        ? null
                        : flexRender(
                            header.column.columnDef.header,
                            header.getContext(),
                          )}
                    </TableHead>
                  ))}
                </TableRow>
              ))}
            </TableHeader>
            <TableBody>
              {loading ? (
                <TableRowsSkeleton columns={4} rows={3} />
              ) : requestTable.getRowModel().rows.length === 0 ? (
                <TableRow>
                  <TableCell colSpan={4} className="h-20 text-center">
                    {t("catalog.requests.empty")}
                  </TableCell>
                </TableRow>
              ) : (
                requestTable.getRowModel().rows.map((row) => (
                  <TableRow key={row.id}>
                    {row.getVisibleCells().map((cell) => (
                      <TableCell key={cell.id}>
                        {flexRender(
                          cell.column.columnDef.cell,
                          cell.getContext(),
                        )}
                      </TableCell>
                    ))}
                  </TableRow>
                ))
              )}
            </TableBody>
          </Table>
        </div>
      </section>

      <Dialog
        open={dialogOpen}
        onOpenChange={(open) => {
          if (
            !open &&
            (operationInFlight ||
              saveLockRef.current.inFlight ||
              form.formState.isSubmitting)
          ) {
            return
          }
          setDialogOpen(open)
          if (!open) {
            resetDialogState()
          }
        }}
      >
        <DialogContent
          className="max-h-[90vh] overflow-y-auto sm:max-w-lg"
          showCloseButton={!operationInFlight && !form.formState.isSubmitting}
        >
          <DialogHeader>
            <DialogTitle>
              {editing
                ? t("catalog.products.editTitle")
                : t("catalog.products.createTitle")}
            </DialogTitle>
            <DialogDescription>
              {t("catalog.products.dialogDescription")}
            </DialogDescription>
          </DialogHeader>

          <Form {...form}>
            <form
              className="space-y-4"
              onSubmit={form.handleSubmit(onSubmit)}
              noValidate
            >
              <FormField
                control={form.control}
                name="name"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>{t("catalog.products.form.name")}</FormLabel>
                    <FormControl>
                      <Input
                        autoComplete="off"
                        {...field}
                        onChange={(event) => {
                          field.onChange(event)
                          const nextCode = nextAutoGeneratedProductCode({
                            name: event.target.value,
                            codeManuallyEdited,
                            preservePersistedCode:
                              editing != null || createdProductId != null,
                          })
                          if (nextCode != null) {
                            form.setValue("code", nextCode, {
                              shouldDirty: true,
                              shouldValidate: true,
                            })
                          }
                        }}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control}
                name="code"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>{t("catalog.products.form.code")}</FormLabel>
                    <FormControl>
                      <Input
                        autoComplete="off"
                        {...field}
                        onChange={(event) => {
                          field.onChange(event)
                          if (editing == null) {
                            setCodeManuallyEdited(true)
                          }
                        }}
                      />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control}
                name="description"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>
                      {t("catalog.products.form.description")}
                    </FormLabel>
                    <FormControl>
                      <Textarea rows={3} {...field} />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <div className="grid gap-3 sm:grid-cols-2">
                <FormField
                  control={form.control}
                  name="price"
                  render={({ field }) => (
                    <FormItem>
                      <FormLabel>{t("catalog.products.form.price")}</FormLabel>
                      <FormControl>
                        <Input
                          inputMode="decimal"
                          placeholder={t("catalog.priceOnRequest")}
                          {...field}
                        />
                      </FormControl>
                      <FormMessage />
                    </FormItem>
                  )}
                />
                <FormField
                  control={form.control}
                  name="currency"
                  render={({ field }) => (
                    <FormItem>
                      <FormLabel>
                        {t("catalog.products.form.currency")}
                      </FormLabel>
                      <FormControl>
                        <Input maxLength={3} {...field} />
                      </FormControl>
                      <FormMessage />
                    </FormItem>
                  )}
                />
              </div>

              <section className="space-y-2 rounded-lg border border-border p-3">
                <p className="text-sm font-medium">{t("taxonomy.assignment")}</p>
                <TaxonomyAssignmentFields
                  control={form.control}
                  options={taxonomyOptions}
                  disabled={!canManage || loading}
                />
              </section>

              {canManage && editing == null ? (
                <div className="space-y-3 rounded-lg border border-border p-3">
                  <p className="text-sm font-medium">
                    {t("catalog.products.files.title")}
                  </p>
                  {pendingFiles.length > 0 ? (
                    <ul className="space-y-2 text-sm">
                      {pendingFiles.map((pending) => (
                        <li
                          key={pending.clientId}
                          className="flex flex-wrap items-center justify-between gap-2"
                        >
                          <span className="min-w-0 truncate">
                            {pending.file.name}{" "}
                            <Badge variant="outline">
                              {pending.visibility === "CustomerVisible"
                                ? t("catalog.products.files.customerVisible")
                                : t("catalog.products.files.internal")}
                            </Badge>
                          </span>
                          <div className="flex items-center gap-2">
                            <PendingFileStatus
                              status={pending.status}
                              error={pending.error}
                            />
                            {pending.status === "error" ? (
                              <Button
                                type="button"
                                size="sm"
                                variant="outline"
                                disabled={operationInFlight || !createdProductId}
                                onClick={() => {
                                  void onRetryPendingFile(pending.clientId)
                                }}
                              >
                                {t("catalog.products.files.retry")}
                              </Button>
                            ) : null}
                          </div>
                        </li>
                      ))}
                    </ul>
                  ) : null}
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-end">
                    <FileVisibilitySelect
                      value={uploadVisibility}
                      disabled={operationInFlight}
                      onValueChange={setUploadVisibility}
                    />
                    <div className="min-w-0 flex-1 space-y-1">
                      <label
                        htmlFor="catalog-product-file-input"
                        className="text-sm font-medium"
                      >
                        {t("catalog.products.files.select")}
                      </label>
                      <Input
                        id="catalog-product-file-input"
                        type="file"
                        multiple
                        disabled={operationInFlight}
                        accept={
                          uploadVisibility === "CustomerVisible"
                            ? CUSTOMER_VISIBLE_FILE_ACCEPT
                            : INTERNAL_FILE_ACCEPT
                        }
                        onChange={(event) => {
                          queueCreateFiles(event.target.files)
                          event.target.value = ""
                        }}
                      />
                    </div>
                  </div>
                  {fileError !== null ? (
                    <p role="alert" className="text-sm text-destructive">
                      {fileError}
                    </p>
                  ) : null}
                </div>
              ) : null}

              {canManage && editing ? (
                <div className="space-y-3 rounded-lg border border-border p-3">
                  <p className="text-sm font-medium">
                    {t("catalog.products.files.title")}
                  </p>
                  {editingPreviewImages.length > 0 ? (
                    <CatalogProductImageGallery
                      images={editingPreviewImages}
                      alt={editing.name}
                      frameClassName="h-40 w-full rounded-lg"
                    />
                  ) : null}
                  <ul className="space-y-2 text-sm">
                    {(editing.files ?? []).map((file) => (
                      <li
                        key={file.id}
                        className="flex flex-wrap items-center justify-between gap-2"
                      >
                        <span className="truncate">
                          {file.fileName}{" "}
                          <Badge variant="outline">
                            {file.visibility === "CustomerVisible"
                              ? t("catalog.products.files.customerVisible")
                              : t("catalog.products.files.internal")}
                          </Badge>
                        </span>
                        <div className="flex gap-2">
                          <Button
                            type="button"
                            size="sm"
                            variant="outline"
                            onClick={() => {
                              void onOpenFile(file.id)
                            }}
                          >
                            {t("catalog.products.files.open")}
                          </Button>
                          <Button
                            type="button"
                            size="sm"
                            variant="ghost"
                            disabled={fileBusy}
                            onClick={() => {
                              void onDeleteFile(file.id)
                            }}
                          >
                            {t("common.delete")}
                          </Button>
                        </div>
                      </li>
                    ))}
                  </ul>
                  <div className="flex flex-col gap-2 sm:flex-row sm:items-end">
                    <FileVisibilitySelect
                      value={uploadVisibility}
                      disabled={fileBusy}
                      onValueChange={setUploadVisibility}
                    />
                    <div className="min-w-0 flex-1 space-y-1">
                      <label
                        htmlFor="catalog-product-file-input"
                        className="text-sm font-medium"
                      >
                        {t("catalog.products.files.select")}
                      </label>
                      <Input
                        id="catalog-product-file-input"
                        type="file"
                        disabled={fileBusy}
                        accept={
                          uploadVisibility === "CustomerVisible"
                            ? CUSTOMER_VISIBLE_FILE_ACCEPT
                            : INTERNAL_FILE_ACCEPT
                        }
                        onChange={(event) => {
                          void onUploadFile(event.target.files?.[0])
                          event.target.value = ""
                        }}
                      />
                    </div>
                  </div>
                  {fileError !== null ? (
                    <p role="alert" className="text-sm text-destructive">
                      {fileError}
                    </p>
                  ) : null}
                </div>
              ) : null}

              {saveBlockers.length > 0 ? (
                <ul className="space-y-1 text-sm text-destructive">
                  {saveBlockers.map((key) => (
                    <li key={key}>{t(key)}</li>
                  ))}
                </ul>
              ) : null}

              <DialogFooter className="-mx-0 -mb-0 border-t-0 bg-transparent p-0">
                <Button
                  type="button"
                  variant="outline"
                  disabled={operationInFlight || form.formState.isSubmitting}
                  onClick={() => {
                    if (operationInFlight || saveLockRef.current.inFlight) {
                      return
                    }
                    setDialogOpen(false)
                  }}
                >
                  {t("common.cancel")}
                </Button>
                <FormPrimaryButton
                  type="submit"
                  isValid={isFormValid}
                  loading={operationInFlight || form.formState.isSubmitting}
                  loadingLabel={t("catalog.products.saving")}
                >
                  {t("catalog.products.save")}
                </FormPrimaryButton>
              </DialogFooter>
            </form>
          </Form>
        </DialogContent>
      </Dialog>

      <Dialog
        open={productPendingDeactivate !== null}
        onOpenChange={(open) => {
          if (!open) {
            setProductPendingDeactivate(null)
          }
        }}
      >
        <DialogContent>
          <DialogHeader>
            <DialogTitle>
              {t("catalog.products.deactivateConfirmTitle")}
            </DialogTitle>
            <DialogDescription>
              {t("catalog.products.deactivateConfirmBody", {
                name: productPendingDeactivate?.name ?? "",
              })}
            </DialogDescription>
          </DialogHeader>
          <DialogFooter>
            <Button
              type="button"
              variant="outline"
              onClick={() => {
                setProductPendingDeactivate(null)
              }}
            >
              {t("common.cancel")}
            </Button>
            <Button
              type="button"
              variant="destructive"
              onClick={() => {
                const product = productPendingDeactivate
                setProductPendingDeactivate(null)
                if (product) {
                  void toggleActive(product)
                }
              }}
            >
              {t("catalog.products.deactivate")}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </div>
  )
}

type CatalogProductsTableMeta = {
  onEdit: (product: CatalogProduct) => void
  onToggleActive: (product: CatalogProduct) => void
  statusBusyId: string | null
}

function CatalogProductActionsCell({ row, table }: CellContext<CatalogProduct, unknown>) {
  const { t } = useTranslation()
  const { onEdit, onToggleActive, statusBusyId } = table.options.meta as CatalogProductsTableMeta
  const product = row.original

  return (
    <div className="flex flex-wrap gap-2">
      <Can permission="catalog.products.manage">
        <Button
          type="button"
          variant="outline"
          size="sm"
          onClick={() => onEdit(product)}
        >
          {t("common.edit")}
        </Button>
        <LoadingButton
          type="button"
          variant="outline"
          size="sm"
          loading={statusBusyId === product.id}
          onClick={() => onToggleActive(product)}
        >
          {product.isActive
            ? t("catalog.products.deactivate")
            : t("catalog.products.activate")}
        </LoadingButton>
      </Can>
    </div>
  )
}

