function FileVisibilitySelect({
  value,
  disabled = false,
  onValueChange,
}: {
  value: CatalogFileVisibility
  disabled?: boolean
  onValueChange: (value: CatalogFileVisibility) => void
}) {
  const { t } = useTranslation()

  return (
    <Select
      modal={false}
      value={value}
      disabled={disabled}
      onValueChange={(next) => {
        if (next === "CustomerVisible" || next === "InternalB2B") {
          onValueChange(next)
        }
      }}
      items={[
        {
          value: "CustomerVisible",
          label: t("catalog.products.files.customerVisible"),
        },
        {
          value: "InternalB2B",
          label: t("catalog.products.files.internal"),
        },
      ]}
    >
      <SelectTrigger disabled={disabled}>
        <SelectValue />
      </SelectTrigger>
      <SelectContent>
        <SelectItem value="CustomerVisible">
          {t("catalog.products.files.customerVisible")}
        </SelectItem>
        <SelectItem value="InternalB2B">
          {t("catalog.products.files.internal")}
        </SelectItem>
      </SelectContent>
    </Select>
  )
}

function PendingFileStatus({
  status,
  error,
}: {
  status: PendingFileStatus
  error?: string
}) {
  const { t } = useTranslation()

  if (status === "waiting") {
    return (
      <span className="text-muted-foreground">
        {t("catalog.products.files.waiting")}
      </span>
    )
  }

  if (status === "sending") {
    return (
      <span className="inline-flex items-center gap-1 text-muted-foreground">
        <Loader2 className="size-3.5 animate-spin" aria-hidden />
        {t("catalog.products.files.sending")}
      </span>
    )
  }

  if (status === "sent") {
    return (
      <span className="inline-flex items-center gap-1">
        <Check className="size-3.5" aria-hidden />
        {t("catalog.products.files.sent")}
      </span>
    )
  }

  return (
    <span className="inline-flex max-w-56 items-center gap-1 text-destructive">
      <CircleAlert className="size-3.5 shrink-0" aria-hidden />
      <span className="truncate">{error ?? t("catalog.products.files.error")}</span>
    </span>
  )
}
