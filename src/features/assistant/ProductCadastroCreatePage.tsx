import { usePermissions } from "@/features/users/permissions/PermissionContext"
import { useVisibleFormIssues } from "@/lib/useVisibleFormIssues"

function emptyProductForm(): CatalogProductFormValues {
  return {
    name: "",
    code: "",
    description: "",
    price: "",
    currency: "BRL",
  }
}

function parsePrice(raw: string): { ok: true; value: number | null } | { ok: false } {
  const trimmed = raw.trim()
  if (trimmed.length === 0) {
    return { ok: true, value: null }
  }
  const parsed = Number(trimmed.replace(",", "."))
  if (!Number.isFinite(parsed) || parsed < 0) {
    return { ok: false }
  }
  return { ok: true, value: parsed }
}

function CreateLeaveGuard({ dirty }: { dirty: boolean }) {
  const { t } = useTranslation()
  const blocker = useBlocker(dirty)
  return (
    <LeaveConfirmDialog
      open={blocker.state === "blocked"}
      title={t("fullPage.leaveConfirm")}
      onStay={() => {
        if (blocker.state === "blocked") blocker.reset()
      }}
      onLeave={() => {
        if (blocker.state === "blocked") blocker.proceed()
      }}
    />
  )
}

export function ProductCadastroCreatePage() {
  const { t } = useTranslation()
  const navigate = useNavigate()
  const { can } = usePermissions()
  const hasDataRouter = useContext(DataRouterContext) != null
  const [creating, setCreating] = useState(false)
  const [createActive, setCreateActive] = useState(true)
  const [codeManuallyEdited, setCodeManuallyEdited] = useState(false)
  const [createdPath, setCreatedPath] = useState<string | null>(null)

  const form = useForm<CatalogProductFormValues>({
    resolver: zodResolver(catalogProductFormSchema),
    defaultValues: emptyProductForm(),
  })
  const watchedValues = useWatch({ control: form.control })
  const parsedForm = catalogProductFormSchema.safeParse(watchedValues)
  const isFormValid = parsedForm.success
  const visibleIssues = useVisibleFormIssues(parsedForm.success ? undefined : parsedForm.error, form)
  const statusDirty = !createActive
  const dirty = createdPath == null && (form.formState.isDirty || statusDirty)

  function fieldMessage(name: string) {
    const key = CATALOG_PRODUCT_FIELD_ISSUE_KEYS[name]
    return key && visibleIssues?.issues.some((issue) => issue.path[0] === name) ? t(key) : undefined
  }

  useEffect(() => {
    if (!createdPath) return
    navigate(createdPath)
  }, [createdPath, navigate])

  useEffect(() => {
    if (!dirty) return
    function warn(event: BeforeUnloadEvent) {
      event.preventDefault()
      event.returnValue = ""
    }
    window.addEventListener("beforeunload", warn)
    return () => window.removeEventListener("beforeunload", warn)
  }, [dirty])

  async function onCreate(values: CatalogProductFormValues) {
    const price = parsePrice(values.price)
    if (!price.ok) {
      form.setError("price", { message: t("catalog.products.invalidPrice") })
      return
    }
    const body: CatalogProductWriteRequest = {
      ...toCatalogProductWriteBody(values, price.value),
      status: createActive ? "Active" : "Inactive",
    }
    setCreating(true)
    try {
      const created = await createCatalogProduct(body)
      toast.success(t("catalog.products.toastCreated"))
      setCreatedPath(`/catalogo/produtos/${encodeURIComponent(created.id)}/cadastro`)
    } catch (error) {
      toast.error(error instanceof Error ? error.message : t("apiErrors.saveCatalogProduct"))
    } finally {
      setCreating(false)
    }
  }

  if (!can("catalog.products.manage")) {
    return <AccessDeniedPage />
  }

  return (
    <div className="cadastro-page">
      {hasDataRouter ? <CreateLeaveGuard dirty={dirty} /> : null}
      <CadastroHeader title={t("cadastro.productCreate")} />
      <Form {...form}>
        <form className="space-y-4 rounded-xl border bg-card p-4 text-card-foreground sm:p-6" onSubmit={form.handleSubmit(onCreate)} noValidate>
          <fieldset disabled={creating} className="space-y-4">
            <FormField
              control={form.control}
              name="name"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>{t("catalog.products.form.name")}</FormLabel>
                  <FormControl>
                    <Input
                      autoComplete="off"
                      {...field}
                      onChange={(event) => {
                        field.onChange(event)
                        const nextCode = nextAutoGeneratedProductCode({
                          name: event.target.value,
                          codeManuallyEdited,
                          preservePersistedCode: false,
                        })
                        if (nextCode != null) {
                          form.setValue("code", nextCode, { shouldDirty: true, shouldValidate: true })
                        }
                      }}
                    />
                  </FormControl>
                  <LiveFieldMessage message={fieldMessage("name")} />
                  <FormMessage />
                </FormItem>
              )}
            />
            <FormField
              control={form.control}
              name="code"
              render={({ field }) => (
                <FormItem>
                  <FormLabel>{t("catalog.products.form.code")}</FormLabel>
                  <FormControl>
                    <Input
                      autoComplete="off"
                      {...field}
                      onChange={(event) => {
                        field.onChange(event)
                        setCodeManuallyEdited(true)
                      }}
                    />
                  </FormControl>
                  <LiveFieldMessage message={fieldMessage("code")} />
                  <FormMessage />
                </FormItem>
              )}
            />
            <div className="grid gap-3 sm:grid-cols-2">
              <FormField
                control={form.control}
                name="price"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>{t("catalog.products.form.price")}</FormLabel>
                    <FormControl>
                      <Input className="tabular-nums" inputMode="decimal" placeholder={t("catalog.priceOnRequest")} {...field} />
                    </FormControl>
                    <FormMessage />
                  </FormItem>
                )}
              />
              <FormField
                control={form.control}
                name="currency"
                render={({ field }) => (
                  <FormItem>
                    <FormLabel>{t("catalog.products.form.currency")}</FormLabel>
                    <FormControl>
                      <Input maxLength={3} {...field} />
                    </FormControl>
                    <LiveFieldMessage message={fieldMessage("currency")} />
                    <FormMessage />
                  </FormItem>
                )}
              />
            </div>
            <div className="space-y-2">
              <span className="block text-sm font-medium">{t("catalog.products.columns.status")}</span>
              <SegmentedControl
                label={t("catalog.products.columns.status")}
                value={createActive ? "active" : "inactive"}
                disabled={creating}
                onChange={(next) => setCreateActive(next === "active")}
                options={[
                  { value: "active", label: t("catalog.products.active") },
                  { value: "inactive", label: t("catalog.products.inactive") },
                ]}
              />
            </div>
          </fieldset>
          <div className="flex flex-wrap justify-end gap-2">
            <Link className={buttonVariants({ variant: "outline" })} to="/catalogo/produtos">
              {t("cadastro.back")}
            </Link>
            <LoadingButton type="submit" loading={creating} disabled={!isFormValid}>
              {t("cadastro.next")}
            </LoadingButton>
          </div>
        </form>
      </Form>
    </div>
  )
}
