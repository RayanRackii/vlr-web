const LIST_PATH = "/catalogo/produtos"

/** Price is defined in the "Preços" step: creation sends price null and the default currency. */
function emptyProductForm(): CatalogProductFormValues {
  return {
    name: "",
    code: "",
    description: "",
    price: "",
    currency: "BRL",
    usesSchedule: true,
  }
}

type CreateFormProps = {
  form: ReturnType<typeof useForm<CatalogProductFormValues>>
  creating: boolean
  showUsesSchedule: boolean
  onCreate: (values: CatalogProductFormValues) => Promise<boolean>
}

/** Step 1 fields. Registers the create call with the shell footer ("Salvar e continuar" / "Salvar e sair"). */
function CreateProductFields({ form, creating, showUsesSchedule, onCreate }: CreateFormProps) {
  const { t } = useTranslation()
  const [codeManuallyEdited, setCodeManuallyEdited] = useState(false)
  const watchedValues = useWatch({ control: form.control })
  const parsedForm = catalogProductFormSchema.safeParse(watchedValues)
  const visibleIssues = useVisibleFormIssues(parsedForm.success ? undefined : parsedForm.error, form)

  useStepSubmit(async () => {
    let created = false
    await form.handleSubmit(async (values) => { created = await onCreate(values) })()
    return created
  })

  function fieldMessage(name: string) {
    const key = CATALOG_PRODUCT_FIELD_ISSUE_KEYS[name]
    return key && visibleIssues?.issues.some((issue) => issue.path[0] === name) ? t(key) : undefined
  }

  return (
    <Form {...form}>
      <form className="space-y-5" onSubmit={(event) => event.preventDefault()} noValidate>
        <fieldset disabled={creating} className="min-w-0 space-y-5">
          <FormField
            control={form.control}
            name="name"
            render={({ field }) => (
              <FormItem>
                <FormLabel>{t("cadastro.product.nameLabel")}</FormLabel>
                <FormControl>
                  <Input
                    autoComplete="off"
                    {...field}
                    onChange={(event) => {
                      field.onChange(event)
                      const nextCode = nextAutoGeneratedProductCode({
                        name: event.target.value,
                        codeManuallyEdited,
                        preservePersistedCode: false,
                      })
                      if (nextCode != null) {
                        form.setValue("code", nextCode, { shouldDirty: true, shouldValidate: true })
                      }
                    }}
                  />
                </FormControl>
                <p className="text-xs text-muted-foreground">{t("cadastro.product.nameHelp")}</p>
                <LiveFieldMessage message={fieldMessage("name")} />
                <FormMessage />
              </FormItem>
            )}
          />
          <FormField
            control={form.control}
            name="code"
            render={({ field }) => (
              <FormItem className="sm:max-w-xs">
                <FormLabel>{t("cadastro.product.codeLabel")}</FormLabel>
                <FormControl>
                  <Input
                    autoComplete="off"
                    {...field}
                    onChange={(event) => {
                      field.onChange(event)
                      setCodeManuallyEdited(true)
                    }}
                  />
                </FormControl>
                <p className="text-xs text-muted-foreground">{t("cadastro.product.codeHelp")}</p>
                <LiveFieldMessage message={fieldMessage("code")} />
                <FormMessage />
              </FormItem>
            )}
          />
          {showUsesSchedule ? (
            <FormField
              control={form.control}
              name="usesSchedule"
              render={({ field }) => (
                <FormItem>
                  <ProductUsesScheduleField value={field.value ?? true} onChange={(next) => field.onChange(next)} disabled={creating} />
                </FormItem>
              )}
            />
          ) : null}
          <FormField
            control={form.control}
            name="description"
            render={({ field }) => (
              <FormItem>
                <FormLabel>{t("cadastro.product.descriptionLabel")}</FormLabel>
                <FormControl>
                  <Textarea rows={4} placeholder={t("cadastro.product.descriptionPlaceholder")} {...field} />
                </FormControl>
                <p className="text-xs text-muted-foreground">{t("cadastro.product.descriptionHelp")}</p>
                <LiveFieldMessage message={fieldMessage("description")} />
                <FormMessage />
              </FormItem>
            )}
          />
        </fieldset>
        <p className="flex items-center gap-2 rounded-lg bg-muted px-4 py-3 text-xs text-muted-foreground">
          <Wallet className="size-4 shrink-0" aria-hidden="true" />
          {t("cadastro.product.pricingInfo")}
        </p>
      </form>
    </Form>
  )
}

export function ProductCadastroCreatePage() {
  const { t } = useTranslation()
  const navigate = useNavigate()
  const { can, activeModules } = usePermissions()
  const rentalsActive = (activeModules ?? []).some((module) => module.trim().toLowerCase() === "rentals")
  const [creating, setCreating] = useState(false)
  const [createdId, setCreatedId] = useState<string | null>(null)
  const createdIdRef = useRef<string | null>(null)
  useBreadcrumbTitle(t("cadastro.productCreate"))

  const form = useForm<CatalogProductFormValues>({
    resolver: zodResolver(catalogProductFormSchema),
    defaultValues: emptyProductForm(),
  })
  const watchedValues = useWatch({ control: form.control })
  const isFormValid = catalogProductFormSchema.safeParse(watchedValues).success
  const dirty = createdId == null && form.formState.isDirty

  /** Creates the product as a draft (Inactive, no price). Resolves true on success. */
  async function onCreate(values: CatalogProductFormValues): Promise<boolean> {
    if (createdIdRef.current) return true
    const body: CatalogProductWriteRequest = {
      ...toCatalogProductWriteBody(values, null),
      status: "Inactive",
    }
    setCreating(true)
    try {
      const created = await createCatalogProduct(body)
      createdIdRef.current = created.id
      setCreatedId(created.id)
      toast.success(t("catalog.products.toastCreated"))
      return true
    } catch (error) {
      toast.error(error instanceof Error ? error.message : t("apiErrors.saveCatalogProduct"))
      return false
    } finally {
      setCreating(false)
    }
  }

  function go(step: CadastroStep) {
    const id = createdIdRef.current
    void navigate(id ? `${LIST_PATH}/${encodeURIComponent(id)}/cadastro?passo=${step}` : LIST_PATH)
  }

  if (!can("catalog.products.manage")) {
    return <AccessDeniedPage />
  }

  return (
    <CadastroShell
      kind="product"
      title={t("cadastro.productCreate")}
      status={{ kind: "draft" }}
      step="dados"
      go={go}
      notApplicable={rentalsActive && watchedValues.usesSchedule === false ? ["agenda", "fila"] : []}
      interactive={false}
      dirty={dirty}
      busy={creating}
      submitDisabled={!isFormValid}
      canPublish={false}
      onPublish={() => undefined}
      onBack={() => void navigate(LIST_PATH)}
    >
      <CreateProductFields form={form} creating={creating} showUsesSchedule={rentalsActive} onCreate={onCreate} />
    </CadastroShell>
  )
}
